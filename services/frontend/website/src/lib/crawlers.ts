/**
 * robots.txt and sitemap.xml, as pure functions.
 *
 * Build-time only: the prerender (`scripts/prerender.mjs`, through
 * `crawler-files.ts`) writes the files into `dist/` when `VITE_SITE_URL` is
 * set, from the pages it has just rendered. This module imports nothing.
 *
 * Generating them at build time is what keeps them true. A committed sitemap
 * rots (a page is added and never crawled), and a committed one with a
 * placeholder domain tells every crawler to go and index a site that is not
 * this one.
 */

export interface CrawlerGroup {
  readonly comment: string
  readonly agents: readonly string[]
  /** `false` writes `Disallow: /` for the group instead. */
  readonly allow: boolean
}

/**
 * The crawlers named in robots.txt, and whether each group may crawl.
 *
 * `User-agent: *` would already let them in. They are named so that a rule
 * added later for one of them cannot quietly shut out the rest, and so that
 * the file says on its face that being found by search engines AND by AI
 * assistants is intended. Training crawlers are allowed too: a model that
 * has read the site is one that can name the business when asked.
 */
export const CRAWLER_GROUPS: readonly CrawlerGroup[] = [
  {
    comment: 'Search engines.',
    agents: ['Googlebot', 'Bingbot'],
    allow: true,
  },
  {
    comment: 'AI search and assistants: what lets ChatGPT, Claude and Perplexity find, cite and recommend the site.',
    agents: ['OAI-SearchBot', 'ChatGPT-User', 'Claude-SearchBot', 'Claude-User', 'PerplexityBot'],
    allow: true,
  },
  {
    comment: 'AI model training. Opting out of this group alone keeps the site findable by the assistants above.',
    agents: ['GPTBot', 'ClaudeBot', 'Google-Extended', 'Applebot-Extended', 'CCBot'],
    allow: true,
  },
]

const HEADER = [
  '# robots.txt, generated by src/lib/crawlers.ts. Edit that, not this file.',
  '#',
  '# Search engines and AI crawlers are named one by one, so a rule added',
  '# later for one of them cannot quietly shut out the others.',
]

const NO_SITEMAP = [
  '# No Sitemap line: it must be an absolute URL on a domain this site owns,',
  '# and none is configured. The build writes one into dist/robots.txt, with',
  '# dist/sitemap.xml and dist/llms.txt, when VITE_SITE_URL is set.',
]

const group = ({ comment, agents, allow }: CrawlerGroup): string =>
  [`# ${comment}`, ...agents.map((agent) => `User-agent: ${agent}`), allow ? 'Allow: /' : 'Disallow: /'].join('\n')

/**
 * @param siteUrl the canonical origin, or '' when none is known. Without one
 *   there is no Sitemap line, rather than one pointing at a domain the site
 *   does not own.
 */
export const robotsTxt = ({
  siteUrl,
  groups: named = CRAWLER_GROUPS,
}: {
  readonly siteUrl: string
  readonly groups?: readonly CrawlerGroup[]
}): string => {
  const groups = [...named, { comment: 'Everyone else.', agents: ['*'], allow: true }].map(group)
  const sitemap = siteUrl === '' ? NO_SITEMAP.join('\n') : `Sitemap: ${siteUrl}/sitemap.xml`
  return `${[HEADER.join('\n'), ...groups, sitemap].join('\n\n')}\n`
}

/** One `hreflang` alternate: this page in one language, or `x-default`. */
export interface SitemapAlternate {
  readonly hrefLang: string
  readonly href: string
}

/** One URL in the sitemap, as the page at it declares itself. */
export interface SitemapPage {
  /** The page's canonical URL, absolute. */
  readonly loc: string
  /** Its `hreflang` alternates, exactly as its head declares them. */
  readonly alternates: readonly SitemapAlternate[]
  /** Its route without the language, which decides its priority. */
  readonly route: string
}

/** Legal pages are real but not what anyone is searching for. */
const priorityFor = (route: string, legal: readonly string[]): string => {
  if (route === '/') return '1.0'
  return legal.includes(route) ? '0.3' : '0.8'
}

const escapeXml = (text: string): string =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

const assertOrigin = (siteUrl: string): void => {
  if (!/^https?:\/\/[^/]+$/.test(siteUrl)) {
    throw new Error(`A sitemap needs an absolute origin with no trailing slash, got "${siteUrl}"`)
  }
}

const onOrigin = (url: string, siteUrl: string): boolean => url === siteUrl || url.startsWith(`${siteUrl}/`)

/**
 * The pages given, each tied to its translations by the `hreflang`
 * alternates its own head declares, so the language versions are understood
 * as one page rather than competing as duplicates, and the sitemap cannot say
 * anything the page does not.
 *
 * Which pages to list is the caller's decision (`crawler-files.ts`: each page
 * that is its own canonical). This refuses only what no sitemap may hold: a
 * URL on another origin, or nothing at all.
 *
 * No `<lastmod>`: the only date available here is the build's, which changes
 * on every deploy whether the page did or not. Google ignores a lastmod it
 * has caught being wrong, so a false one costs more than none.
 */
export const sitemapXml = ({
  siteUrl,
  pages,
  legalRoutes = [],
}: {
  readonly siteUrl: string
  readonly pages: readonly SitemapPage[]
  readonly legalRoutes?: readonly string[]
}): string => {
  assertOrigin(siteUrl)
  if (pages.length === 0) throw new Error('Refusing to write a sitemap with no pages')
  const foreign = pages
    .flatMap((page) => [page.loc, ...page.alternates.map((alternate) => alternate.href)])
    .filter((url) => !onOrigin(url, siteUrl))
  if (foreign.length > 0) {
    throw new Error(`A sitemap lists only URLs on ${siteUrl}, got "${foreign.join('", "')}"`)
  }

  const entries = pages.map((page) =>
    [
      '  <url>',
      `    <loc>${escapeXml(page.loc)}</loc>`,
      ...page.alternates.map(
        (alternate) =>
          `    <xhtml:link rel="alternate" hreflang="${escapeXml(alternate.hrefLang)}" href="${escapeXml(alternate.href)}"/>`,
      ),
      `    <priority>${priorityFor(page.route, legalRoutes)}</priority>`,
      '  </url>',
    ].join('\n'),
  )

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated at build time by src/lib/crawlers.ts. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${entries.join('\n')}
</urlset>
`
}
